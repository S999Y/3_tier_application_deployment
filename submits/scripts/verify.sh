#!/usr/bin/env bash
# Run the assignment's functional tests and write a temporary, redacted
# evidence report. The submitted evidence lives in submits/README.md.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"
OUT="${VERIFY_OUT:-${TMPDIR:-/tmp}/assignment15-evidence-$$.md}"
BASE_URL="${BASE_URL:-http://localhost}"

# Load teacher/DB credentials without printing them.
set -a
# shellcheck disable=SC1091
. "$ROOT/k8s/backend.env"
set +a
TEACHER_USER="${DJANGO_SUPERUSER_USERNAME:-teacher}"
TEACHER_PASS="${DJANGO_SUPERUSER_PASSWORD:?DJANGO_SUPERUSER_PASSWORD is missing}"
POSTGRES_USER="${POSTGRES_USER:-results}"
POSTGRES_DB="${POSTGRES_DB:-results}"

start_code() { printf '\n```text\n'; }
end_code() { printf '```\n'; }

{
  echo "# Evidence — Three-Tier Kubernetes Deployment"
  echo
  echo "Generated by \`submits/scripts/verify.sh\` on $(date -u +'%Y-%m-%dT%H:%M:%SZ')."
  echo
  echo "Environment: Docker Desktop Kubernetes; local registry \`localhost:5000\`;"
  echo "browser entry point \`$BASE_URL/\`."
  echo
  echo "> Credentials and authentication tokens are redacted. No Secret values are printed."
} > "$OUT"

echo "==> 1. Image registry"
{
  echo
  echo "## 1. Image Registry"
  echo
  echo "Both application images were built and published to the local registry that the cluster pulls from."
  start_code
  echo "# Registry catalog"
  curl -sS http://localhost:5000/v2/_catalog
  echo
  echo
  echo "# Published images"
  docker images --format '{{.Repository}}:{{.Tag}} {{.ID}}' | grep 'localhost:5000/result' || true
  end_code
} >> "$OUT"

echo "==> 2. Cluster and storage"
{
  echo
  echo "## 2. Cluster and Storage"
  echo
  echo "Node readiness, default StorageClass, and the dedicated namespaces."
  start_code
  kubectl version 2>&1 || true
  echo
  echo "# Nodes"
  kubectl get nodes -o wide
  echo
  echo "# StorageClasses"
  kubectl get storageclass
  echo
  echo "# Namespaces"
  kubectl get namespaces
  end_code
} >> "$OUT"

echo "==> 3. Workload readiness"
{
  echo
  echo "## 3. Workload Readiness"
  echo
  echo "Pods, Deployments, StatefulSets, the migration Job, ConfigMaps, Secret names,"
  echo "the backend readiness probe, Redis persistence arguments, and migration/teacher logs."
  echo "Secret values are never printed."
  start_code
  echo "# Pods - app"
  kubectl get pods -n app -o wide
  echo
  echo "# Pods - db-production"
  kubectl get pods -n db-production -o wide
  echo
  echo "# Deployments, StatefulSets, Jobs - app"
  kubectl get deploy,sts,job -n app
  echo
  echo "# StatefulSets - db-production"
  kubectl get sts -n db-production
  echo
  echo "# ConfigMaps - app"
  kubectl get configmap -n app
  echo
  echo "# Secrets (names/types only)"
  kubectl get secret -n app
  kubectl get secret -n db-production
  echo
  echo "# Backend readiness probe"
  kubectl get deployment backend -n app \
    -o jsonpath='{.spec.template.spec.containers[0].readinessProbe}'
  echo
  echo
  echo "# Redis persistence arguments"
  kubectl get statefulset redis -n app \
    -o jsonpath='{.spec.template.spec.containers[0].args}'
  echo
  echo
  echo "# Migration Job logs (migrations + teacher account)"
  kubectl logs -n app job/django-migrate --tail=80 2>&1 || true
  end_code
} >> "$OUT"

echo "==> 4. Services, endpoints, ingress"
{
  echo
  echo "## 4. Services, Endpoints, and Ingress"
  echo
  echo "The data Services are internal (ClusterIP/headless). The frontend and backend"
  echo "Services have populated Endpoints, and the Ingress exposes the app on localhost."
  start_code
  echo "# Services - app"
  kubectl get svc -n app
  echo
  echo "# Services - db-production"
  kubectl get svc -n db-production
  echo
  echo "# Endpoints - app"
  kubectl get endpoints -n app 2>/dev/null
  echo
  echo "# Endpoints - db-production"
  kubectl get endpoints -n db-production 2>/dev/null
  echo
  echo "# Ingress - app"
  kubectl get ingress -n app
  echo
  echo "# ingress-nginx controller Service"
  kubectl get svc -n ingress-nginx
  end_code
} >> "$OUT"

echo "==> 5. Persistent volume claims"
{
  echo
  echo "## 5. Persistent Volume Claims"
  echo
  echo "Redis and PostgreSQL each have a dynamically provisioned, bound PVC."
  start_code
  echo "# PVCs - app"
  kubectl get pvc -n app
  echo
  echo "# PVCs - db-production"
  kubectl get pvc -n db-production
  echo
  echo "# PersistentVolumes"
  kubectl get pv
  end_code
} >> "$OUT"

echo "==> 6. Health through the frontend"
{
  echo
  echo "## 6. Health Check Through the Frontend"
  echo
  echo "The browser entry point goes through ingress-nginx to the frontend Nginx,"
  echo "which proxies \`/api/\` to the Django backend."
  start_code
  echo "# GET ${BASE_URL}/api/health/  (ingress -> frontend Nginx -> backend)"
  curl -sS "${BASE_URL}/api/health/"
  echo
  echo "# GET ${BASE_URL}/  (React SPA through ingress -> frontend)"
  curl -sS -o /dev/null -w "HTTP %{http_code}\n" "${BASE_URL}/"
  end_code
} >> "$OUT"

echo "==> 7. Teacher login and CSV upload"
LOGIN_JSON="$(curl -sS -X POST "${BASE_URL}/api/auth/login/" \
  -H "Content-Type: application/json" \
  -d "{\"username\":\"${TEACHER_USER}\",\"password\":\"${TEACHER_PASS}\"}")"
TOKEN="$(printf '%s' "$LOGIN_JSON" | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')"
if [ -z "$TOKEN" ]; then
  echo "ERROR: teacher login failed: $LOGIN_JSON" >&2
  exit 1
fi
REDACTED_LOGIN="$(printf '%s' "$LOGIN_JSON" | sed -E 's/"token"[[:space:]]*:[[:space:]]*"[^"]*"/"token":"<REDACTED>"/')"
{
  echo
  echo "## 7. Teacher Login and CSV Upload"
  echo
  echo "The teacher authenticates and uploads the sample CSV. The token is redacted."
  start_code
  echo "# POST ${BASE_URL}/api/auth/login/ (token redacted)"
  printf '%s\n' "$REDACTED_LOGIN"
  echo
  echo "# POST ${BASE_URL}/api/results/upload/ (backend/sample_results.csv)"
  curl -sS -X POST "${BASE_URL}/api/results/upload/" \
    -H "Authorization: Token ${TOKEN}" \
    -F "file=@backend/sample_results.csv"
  echo
  end_code
} >> "$OUT"

echo "==> 8. Cache behaviour"
{
  echo
  echo "## 8. Redis Cache Behaviour"
  echo
  echo "The upload cleared the affected cache key, so the first lookup reads PostgreSQL"
  echo "and the second lookup is served from Redis."
  start_code
  echo "# First lookup (expected: source = database)"
  curl -sS "${BASE_URL}/api/results/STU001/"
  echo
  echo
  echo "# Second lookup (expected: source = cache)"
  curl -sS "${BASE_URL}/api/results/STU001/"
  echo
  echo
  echo "# Redis keys"
  kubectl exec -n app redis-0 -- redis-cli KEYS '*'
  end_code
} >> "$OUT"

echo "==> 9. PostgreSQL persistence"
{
  echo
  echo "## 9. PostgreSQL Pod Recreation and Persistence"
  echo
  echo "The PostgreSQL Pod is deleted and recreated. The PVC is unchanged. Redis is"
  echo "flushed so the next lookup must read PostgreSQL, proving the rows survived."
  start_code
  echo "# PostgreSQL pod before deletion"
  kubectl get pod postgres-0 -n db-production -o wide
  echo
  echo "# PVC before deletion"
  kubectl get pvc -n db-production
  echo
  echo "# Deleting postgres-0"
  kubectl delete pod postgres-0 -n db-production
  echo
  echo "# Waiting for the StatefulSet to recover"
  kubectl rollout status statefulset/postgres -n db-production --timeout=300s
  echo
  echo "# PostgreSQL pod after recovery"
  kubectl get pod postgres-0 -n db-production -o wide
  echo
  echo "# PVC after recovery (same volume)"
  kubectl get pvc -n db-production
  echo
  echo "# Flushing Redis so the next lookup must read PostgreSQL"
  kubectl exec -n app redis-0 -- redis-cli FLUSHALL
  echo
  echo "# Lookup after pod recreation (expected: source = database, same marks)"
  curl -sS "${BASE_URL}/api/results/STU001/"
  echo
  echo
  echo "# Row count in PostgreSQL"
  kubectl exec -n db-production postgres-0 -- \
    psql -U "$POSTGRES_USER" -d "$POSTGRES_DB" -c "SELECT COUNT(*) FROM results_result;"
  end_code
} >> "$OUT"

echo
echo "Temporary evidence report: $OUT"
echo "Submitted evidence: submits/README.md"
